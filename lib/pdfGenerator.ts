import PDFDocument from 'pdfkit';

interface Poll {
    id: string;
    question_text: string;
    option_a: string;
    option_b: string;
    option_c: string;
    option_d: string;
    correct_option: 'A' | 'B' | 'C' | 'D';
}

// Module-level font cache to avoid repeated network fetches across calls
let cachedRegularFont: Buffer | null = null;
let cachedBoldFont: Buffer | null = null;

const REGULAR_FONT_URL = 'https://cdn.jsdelivr.net/gh/google/fonts@main/ofl/abhayalibre/AbhayaLibre-Regular.ttf';
const BOLD_FONT_URL    = 'https://cdn.jsdelivr.net/gh/google/fonts@main/ofl/abhayalibre/AbhayaLibre-Bold.ttf';

/**
 * Fetches the Abhaya Libre (bilingual Sinhala/English) fonts from CDN.
 * Results are cached in memory for the lifetime of the server process.
 */
async function loadFonts(): Promise<void> {
    if (cachedRegularFont && cachedBoldFont) return;

    const [regResp, boldResp] = await Promise.all([fetch(REGULAR_FONT_URL), fetch(BOLD_FONT_URL)]);

    if (!regResp.ok || !boldResp.ok) {
        throw new Error(`Font download failed: ${regResp.status} / ${boldResp.status}`);
    }

    [cachedRegularFont, cachedBoldFont] = await Promise.all([
        regResp.arrayBuffer().then(buf => Buffer.from(buf)),
        boldResp.arrayBuffer().then(buf => Buffer.from(buf)),
    ]);
}

/**
 * Draws a footer on the current page. A re-entrancy guard prevents recursion
 * caused by the 'pageAdded' event firing during footer rendering itself.
 */
// eslint-disable-next-line @typescript-eslint/no-explicit-any
function drawFooter(doc: any, isDrawing: { value: boolean }): void {
    if (isDrawing.value) return;
    isDrawing.value = true;
    try {
        const margin = 50;
        const savedY: number = doc.y;
        doc.fontSize(9)
            .fillColor('#95a5a6')
            .font('Bilingual')
            .text(
                `Generated by E-Class Bot - පද්ධතිය මගින් ස්වයංක්‍රීයව සකසන ලද්දකි - ${new Date().toLocaleDateString()}`,
                margin,
                doc.page.height - 40,
                { align: 'center', width: doc.page.width - margin * 2 }
            );
        doc.y = savedY;
    } finally {
        isDrawing.value = false;
    }
}

/**
 * Generates an official bilingual (Sinhala & English) Answer Key PDF
 * for a given Quiz Set.
 *
 * @param setTitle - Display title for the quiz set.
 * @param polls    - Ordered array of poll/question objects.
 * @returns        A Buffer containing the complete PDF.
 */
export async function generateAnswerKey(setTitle: string, polls: Poll[]): Promise<Buffer> {
    await loadFonts(); // ensure fonts are ready before streaming

    return new Promise<Buffer>((resolve, reject) => {
        try {
            const doc = new PDFDocument({ margin: 50, autoFirstPage: true });
            const chunks: Buffer[] = [];
            const isDrawing = { value: false }; // re-entrancy guard passed by reference

            doc.on('data', chunk => chunks.push(chunk));
            doc.on('end', () => resolve(Buffer.concat(chunks)));
            doc.on('error', reject);

            doc.registerFont('Bilingual', cachedRegularFont!);
            doc.registerFont('BilingualBold', cachedBoldFont!);
            doc.on('pageAdded', () => drawFooter(doc, isDrawing));

            // ── HEADER ────────────────────────────────────────────────────────
            doc.font('BilingualBold').fontSize(20).fillColor('#2c3e50').text(setTitle.toUpperCase(), { align: 'center' });
            doc.font('Bilingual').fontSize(14).fillColor('#34495e').text('OFFICIAL ANSWER KEY & REVIEW SHEET', { align: 'center' });
            doc.moveDown(0.8);
            doc.strokeColor('#bdc3c7').lineWidth(1).moveTo(50, doc.y).lineTo(doc.page.width - 50, doc.y).stroke();
            doc.moveDown(1.2);

            // ── QUESTIONS ─────────────────────────────────────────────────────
            const optionKeys = ['A', 'B', 'C', 'D'] as const;

            for (let i = 0; i < polls.length; i++) {
                const p = polls[i];

                // Smart pagination: ensure enough room for a full question block
                if (doc.y + 120 > doc.page.height - 50) doc.addPage();

                doc.font('BilingualBold').fontSize(13).fillColor('#2c3e50')
                    .text(`${i + 1}. ${p.question_text}`, { width: 500, align: 'left' });
                doc.moveDown(0.4);

                for (const key of optionKeys) {
                    const text = p[`option_${key.toLowerCase()}` as keyof Poll] as string;
                    const isCorrect = key === p.correct_option;
                    const cursorY: number = doc.y;

                    doc.font(isCorrect ? 'BilingualBold' : 'Bilingual')
                        .fontSize(12)
                        .fillColor(isCorrect ? '#27ae60' : '#7f8c8d')
                        .text(isCorrect ? '✓' : '○', 70, cursorY);

                    doc.font('Bilingual').fontSize(11).fillColor('#2c3e50')
                        .text(`${key}) ${text}`, 95, cursorY, { width: 340, align: 'left' });

                    if (isCorrect) {
                        doc.font('Bilingual').fontSize(9).fillColor('#27ae60')
                            .text('නිවැරදි පිළිතුර', 445, cursorY, { width: 85, align: 'right' });
                    }

                    doc.moveDown(0.3);
                }

                doc.moveDown(0.8);
            }

            doc.end();
        } catch (error) {
            reject(error);
        }
    });
}