import PDFDocument from 'pdfkit';

/**
 * INTERNAL TYPES
 */
interface Poll {
    id: string;
    question_text: string;
    option_a: string;
    option_b: string;
    option_c: string;
    option_d: string;
    correct_option: 'A' | 'B' | 'C' | 'D';
}

// Global cache to avoid repeated network requests during the same server session
let cachedRegularFont: Buffer | null = null;
let cachedBoldFont: Buffer | null = null;

// Use jsDelivr CDN (more reliable than raw GitHub)
const REGULAR_FONT_URL = 'https://cdn.jsdelivr.net/gh/google/fonts@main/ofl/abhayalibre/AbhayaLibre-Regular.ttf';
const BOLD_FONT_URL = 'https://cdn.jsdelivr.net/gh/google/fonts@main/ofl/abhayalibre/AbhayaLibre-Bold.ttf';

/**
 * HELPER: CDN FONT LOADER
 * Fetches the Abhaya Libre (Bilingual) fonts from the Google Fonts CDN.
 * Uses a global cache to minimize bandwidth and latency.
 */
async function loadFonts(): Promise<void> {
    if (cachedRegularFont && cachedBoldFont) return;

    try {
        const [regResp, boldResp] = await Promise.all([
            fetch(REGULAR_FONT_URL),
            fetch(BOLD_FONT_URL)
        ]);

        if (!regResp.ok || !boldResp.ok) {
            throw new Error(`Font download failed: ${regResp.status} / ${boldResp.status}`);
        }

        cachedRegularFont = Buffer.from(await regResp.arrayBuffer());
        cachedBoldFont = Buffer.from(await boldResp.arrayBuffer());
    } catch (err) {
        console.error('[PDF] Critical Font Load Error:', err);
        throw err; // Re-throw to prevent generating corrupted/unfonted PDFs
    }
}

// State guard to prevent footer recursion or overlap
let isDrawingFooter = false;

/**
 * HELPER: PAGE FOOTER
 * Draws the bilingual bot attribution and generation date at the bottom of every page.
 */
function drawFooter(doc: any): void {
    if (isDrawingFooter) return;
    isDrawingFooter = true;
    try {
        const margin = 50;
        const bottom = doc.page.height - 40;
        const savedY = doc.y;

        doc.fontSize(9)
            .fillColor('#95a5a6')
            .font('Bilingual')
            .text(
                `Generated by E-Class Bot - පද්ධතිය මගින් ස්වයංක්‍රීයව සකසන ලද්දකි - ${new Date().toLocaleDateString()}`,
                margin,
                bottom,
                { align: 'center', width: doc.page.width - (margin * 2) }
            );

        doc.y = savedY;
    } finally {
        isDrawingFooter = false;
    }
}

/**
 * BILINGUAL PDF GENERATOR (Sinhala & English)
 * Generates an official Answer Key and Review Sheet for a specific Quiz Set.
 * 
 * @param setTitle - The title of the Quiz Set (e.g., 'Mechanics Week 01').
 * @param polls - Array of poll/question objects to include.
 * @returns A promise resolving to the final PDF Buffer.
 */
export async function generateAnswerKey(setTitle: string, polls: Poll[]): Promise<Buffer> {
    // 1. Ensure fonts are loaded before starting PDF stream
    await loadFonts();

    return new Promise((resolve, reject) => {
        try {
            // 2. Initialize PDF Document
            const doc = new PDFDocument({
                margin: 50,
                autoFirstPage: true
            });
            const chunks: Buffer[] = [];

            // 3. Stream Setup
            doc.on('data', (chunk) => chunks.push(chunk));
            doc.on('end', () => resolve(Buffer.concat(chunks)));
            doc.on('error', (err) => reject(err));

            // 4. Register Multi-language Fonts
            doc.registerFont('Bilingual', cachedRegularFont!);
            doc.registerFont('BilingualBold', cachedBoldFont!);

            // 5. Global Page Events
            doc.on('pageAdded', () => drawFooter(doc));

            // ========== HEADER SECTION ==========
            doc.font('BilingualBold')
                .fontSize(20)
                .fillColor('#2c3e50')
                .text(setTitle.toUpperCase(), { align: 'center' });

            doc.font('Bilingual')
                .fontSize(14)
                .fillColor('#34495e')
                .text('OFFICIAL ANSWER KEY & REVIEW SHEET', { align: 'center' });

            doc.moveDown(0.8);

            // Divider line
            doc.strokeColor('#bdc3c7')
                .lineWidth(1)
                .moveTo(50, doc.y)
                .lineTo(doc.page.width - 50, doc.y)
                .stroke();

            doc.moveDown(1.2);

            // ========== QUESTIONS SECTION ==========
            for (let i = 0; i < polls.length; i++) {
                const p = polls[i];
                const questionNum = i + 1;

                // SMART PAGINATION: Reserve space for Question + Options block (approx ~120 units)
                const requiredHeight = 120;
                if (doc.y + requiredHeight > doc.page.height - 50) {
                    doc.addPage();
                }

                // Question Title
                doc.font('BilingualBold')
                    .fontSize(13)
                    .fillColor('#2c3e50')
                    .text(`${questionNum}. ${p.question_text}`, {
                        width: 500,
                        align: 'left'
                    });

                doc.moveDown(0.4);

                // Option Matrix
                const options = [
                    { key: 'A', text: p.option_a },
                    { key: 'B', text: p.option_b },
                    { key: 'C', text: p.option_c },
                    { key: 'D', text: p.option_d }
                ];

                options.forEach(opt => {
                    const isCorrect = opt.key === p.correct_option;
                    const cursorY = doc.y;

                    // Option Indicator (Checkmark for correct, Circle for others)
                    doc.font(isCorrect ? 'BilingualBold' : 'Bilingual')
                        .fontSize(12)
                        .fillColor(isCorrect ? '#27ae60' : '#7f8c8d');

                    doc.text(isCorrect ? '✓' : '○', 70, cursorY);

                    // Option Content
                    doc.font('Bilingual')
                        .fontSize(11)
                        .fillColor('#2c3e50')
                        .text(`${opt.key}) ${opt.text}`, 95, cursorY, {
                            width: 340,
                            align: 'left'
                        });

                    // Verification Badge (Sinhala)
                    if (isCorrect) {
                        doc.font('Bilingual')
                            .fontSize(9)
                            .fillColor('#27ae60')
                            .text('නිවැරදි පිළිතුර', 445, cursorY, {
                                width: 85,
                                align: 'right'
                            });
                    }

                    doc.moveDown(0.3);
                });

                doc.moveDown(0.8); // Spacer between question blocks
            }

            // 6. Finalize the stream
            doc.end();
        } catch (error) {
            reject(error);
        }
    });
}